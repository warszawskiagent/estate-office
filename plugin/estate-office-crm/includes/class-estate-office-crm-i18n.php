    /**
     * @return array<int, string>
     */
    public static function supported_languages(): array
    {
        return ['pl_PL', 'en_US', 'de_DE', 'uk_UA'];
    }

    public static function normalize_language(string $language): string
    {
        $language = trim($language);
        return in_array($language, self::supported_languages(), true) ? $language : 'en_US';
    }

    public static function translate_html(string $html, string $language): string
    {
        $language = self::normalize_language($language);
        if ($language === 'pl_PL' || $html === '') {
            return $html;
        }

        $map = self::dictionary($language);
        if (empty($map)) {
            return $html;
        }

        $keys = array_keys($map);
        usort($keys, static function (string $a, string $b): int {
            return strlen($b) <=> strlen($a);
        });

        $ordered = [];
        foreach ($keys as $key) {
            $ordered[$key] = (string) ($map[$key] ?? $key);
        }

        return strtr($html, $ordered);
    }

    public static function translate_text(string $text, string $language): string
    {
        $language = self::normalize_language($language);
        if ($language === 'pl_PL' || $text === '') {
            return $text;
        }

        $map = self::dictionary($language);
        return isset($map[$text]) ? (string) $map[$text] : $text;
    }

